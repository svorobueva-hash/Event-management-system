CREATE OR REPLACE VIEW документы_выездных_мероприятий AS
SELECT
    m.название_мероприятия,
    m.дата_проведения,
    s.фио AS ответственный_сотрудник,

    STRING_AGG(
        DISTINCT d.название_документа,
        ', ' ORDER BY d.название_документа
    ) AS название_документа,

    STRING_AGG(
        DISTINCT d.предмет_документа,
        ', ' ORDER BY d.предмет_документа
    ) AS предмет_документа,

    STRING_AGG(
        DISTINCT d.регистрационный_номер,
        ', ' ORDER BY d.регистрационный_номер
    ) AS регистрационный_номер,

    COUNT(DISTINCT r.id_регистрации) AS количество_регистраций,

    total.всего_участниц AS всего_участниц_на_мероприятии

FROM организация_мероприятий AS o

JOIN регистрация_участников AS r
    ON o.id_регистрации = r.id_регистрации

JOIN мероприятия AS m
    ON r.id_мероприятия = m.id_мероприятия

JOIN сотрудники AS s
    ON o.id_сотрудника = s.id_сотрудника

JOIN пакет_документов AS d
    ON o.id_пакета_документов = d.id_пакета_документов

JOIN (
    SELECT
        id_мероприятия,
        COUNT(DISTINCT id_участника) AS всего_участниц
    FROM регистрация_участников
    GROUP BY id_мероприятия
) AS total
    ON total.id_мероприятия = m.id_мероприятия

WHERE m.название_мероприятия = 'Кубок Москвы по чир спорту'

GROUP BY
    m.название_мероприятия,
    m.дата_проведения,
    s.id_сотрудника,
    s.фио,
    total.всего_участниц

ORDER BY s.фио;
