CREATE VIEW анализ_взносов_по_мероприятиям AS
SELECT
    m.название_мероприятия,
    m.дата_проведения,

    COUNT(DISTINCT r.id_участника) AS количество_участниц,

    MIN(u.взнос_участников)
        FILTER (WHERE u.взнос_участников > 0)
        AS минимальный_взнос,

    MAX(u.взнос_участников)
        FILTER (WHERE u.взнос_участников > 0)
        AS максимальный_взнос,

    ROUND(
        AVG(u.взнос_участников)
        FILTER (WHERE u.взнос_участников > 0), 2
    ) AS средний_взнос,

    COUNT(*) FILTER (
        WHERE r.отметка_о_взносе = false
        AND u.взнос_участников > 0
    ) AS неоплаченные_регистрации,

    COALESCE(
        SUM(u.взнос_участников)
        FILTER (WHERE r.отметка_о_взносе = true),
        0
    ) AS получено_взносов

FROM регистрация_участников AS r

JOIN участники AS u
    ON r.id_участника = u.id_участника

JOIN мероприятия AS m
    ON r.id_мероприятия = m.id_мероприятия

GROUP BY
    m.id_мероприятия,
    m.название_мероприятия,
    m.дата_проведения

ORDER BY m.дата_проведения;
