CREATE VIEW неоплаченные_взносы AS
SELECT
    n.фио,
    m.название_мероприятия,
    m.дата_проведения,
    n.взнос_участников,
    s.статус_участия
FROM регистрация_участников AS s
JOIN участники AS n
    ON n.id_участника = s.id_участника
JOIN мероприятия AS m
    ON m.id_мероприятия = s.id_мероприятия
WHERE s.отметка_о_взносе = false;
